def install_missing_tool(name: str, timeout: int = 300) -> bool:
    """Check if `name` is installed; if not, install it via Go or pip."""
    ensure_tool_paths()
    if name in PYTHON_PACKAGES:
        mod_name, spec = PYTHON_PACKAGES[name]
        if importlib.util.find_spec(mod_name) is not None:
            return True
        LOG.info("installing missing Python package %s (%s)...", name, spec)
        try:
            subprocess.run(
                [sys.executable, "-m", "pip", "install", "--quiet", spec],
                check=True,
                timeout=timeout,
            )
            if name == "playwright":
                subprocess.run(
                    [sys.executable, "-m", "playwright", "install", "chromium"],
                    check=False,
                    timeout=timeout,
                )
            return importlib.util.find_spec(mod_name) is not None
        except (OSError, subprocess.SubprocessError) as exc:
            LOG.warning("failed to install Python package %s: %s", name, exc)
            return False

    if shutil.which(name):
        return True
    if name not in EXTERNAL_TOOLS:
        return False

    installer, spec = EXTERNAL_TOOLS[name]
    if installer == "go":
        go_bin = shutil.which("go")
        if not go_bin:
            LOG.warning("cannot auto-install %s: 'go' compiler not found in PATH", name)
            return False
        LOG.info("installing missing tool %s via 'go install %s'...", name, spec)
        try:
            env = os.environ.copy()
            env.setdefault("CGO_ENABLED", "0")
            subprocess.run(
                [go_bin, "install", spec],
                check=True,
                timeout=timeout,
                env=env,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            LOG.warning("failed to install %s via go: %s", name, exc)
            return False
    elif installer == "git-go":
        go_bin = shutil.which("go")
        git_bin = shutil.which("git")
        if not go_bin or not git_bin:
            LOG.warning("cannot auto-install %s: 'go' and 'git' are required in PATH", name)
            return False
        LOG.info("installing missing tool %s from source (%s)...", name, spec)
        try:
            env = os.environ.copy()
            env.setdefault("CGO_ENABLED", "0")
            with tempfile.TemporaryDirectory() as tmpdir:
                subprocess.run(
                    [git_bin, "clone", "--depth", "1", spec, tmpdir],
                    check=True,
                    timeout=timeout,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
                subprocess.run(
                    [go_bin, "install", "."],
                    cwd=tmpdir,
                    check=True,
                    timeout=timeout,
                    env=env,
                )
        except (OSError, subprocess.SubprocessError) as exc:
            LOG.warning("failed to build %s from source: %s", name, exc)
            return False
    elif installer == "pip":
        LOG.info("installing missing tool %s via pip (%s)...", name, spec)
        try:
            subprocess.run(
                [sys.executable, "-m", "pip", "install", "--quiet", spec],
                check=True,
                timeout=timeout,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            LOG.warning("failed to install %s via pip: %s", name, exc)
            return False

    ensure_tool_paths()
    installed_path = shutil.which(name)
    if installed_path:
        LOG.info("tool %s installed at %s", name, installed_path)
        return True
    LOG.warning("tool %s still not found in PATH after installation attempt", name)
    return False


