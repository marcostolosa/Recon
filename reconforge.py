    def analyze_js(self, url: str, body: str):
        if url in self.js_saved:
            return
        self.js_saved.add(url)
        digest = hashlib.sha256(url.encode()).hexdigest()[:20]
        target = self.js_dir / f"{digest}.js"
        target.write_text(body, encoding="utf8")
        for match in URL_REGEX.finditer(body):
            raw = match.group("url")
            if "${" not in raw and not raw.startswith("//"):
                self.put_url(raw, "js_static", url)
        for match in JS_RELATIVE.finditer(body):
            raw = match.group(1)
            if raw.startswith(("http://", "https://", "/")):
                self.put_url(raw, "js_call", url)
            elif not raw.startswith((".", "?", "#")) and not re.match(r"[\w-]+\.[\w-]+$", raw):
                root = urlsplit(url)
                self.put_url(f"{root.scheme}://{root.netloc}/" + raw.lstrip("/"), "js_call")
        sm = SOURCEMAP.search(body)
        if sm:
            self.put_url(sm.group(1), "source_map", url)
        for kind, rx in SECRET_PATTERNS.items():
            for match in rx.finditer(body):
                self.store.secret(kind, match.group(), url, body.count("\n", 0, match.start()) + 1)

    def extract(self, url: str, content_type: str, payload: bytes):
        ct = content_type.lower()
        path = urlsplit(url).path.lower()
        if ("javascript" in ct or path.endswith((".js", ".mjs"))) and not url.endswith(".map"):
            self.analyze_js(url, payload.decode("utf-8", "replace"))
            return
        if path.endswith(".map") or "sourcemap" in ct:
            try:
                data = json.loads(payload)
                for i, source in enumerate(data.get("sourcesContent", [])[:60]):
                    if isinstance(source, str):
                        self.analyze_js(f"{url}#source{i}", source[: self.a.max_body])
            except (json.JSONDecodeError, ValueError, TypeError):
                pass
            return
        if "html" in ct:
            html = payload.decode("utf-8", "replace")
            parser = HTMLLinks()
            parser.feed(html)
            for link in parser.links:
                self.put_url(link, "html", url)
            for form in parser.forms:
                if form["action"]:
                    self.put_url(
                        form["action"],
                        "html_form_" + form["method"].lower(),
                        url,
                        probe=form["method"] == "GET",
                    )
            return
        if path.endswith("robots.txt"):
            txt = payload.decode("utf-8", "replace")
            for line in txt.splitlines():
                m = re.match(r"\s*(?:Sitemap|Disallow|Allow)\s*:\s*(\S+)", line, re.I)
                if m and m.group(1) != "/":
                    self.put_url(m.group(1), "robots", url)
            return
        if "xml" in ct or path.endswith(".xml"):
            try:
                root = ET.fromstring(payload)
                for el in root.iter():
                    if el.tag.endswith("}loc") or el.tag == "loc":
                        if el.text:
                            self.put_url(el.text, "sitemap", url)
            except ET.ParseError:
                pass
            return
        if "json" in ct or path.endswith(".json"):
            try:
                data = json.loads(payload)
                # Parse OpenAPI / Swagger endpoints
                if isinstance(data, dict):
                    paths = data.get("paths", {})
                    if isinstance(paths, dict):
                        for endpoint in paths.keys():
                            if isinstance(endpoint, str) and endpoint.startswith("/"):
                                self.put_url(endpoint, "openapi_path", url)
                # Scan for URLs in strings
                text = payload.decode("utf-8", "replace")
                for match in URL_REGEX.finditer(text):
                    raw = match.group("url")
                    if not raw.startswith("//"):
                        self.put_url(raw, "json_ref", url)
            except (json.JSONDecodeError, ValueError, UnicodeError):
                pass

    async def probe(self, url: str):
        p = urlsplit(url)
        if not p.hostname or not await self.resolves(p.hostname):
            self.store.finish(url, {"error": "unresolvable_or_non_public_dns"})
            return
        async with self.sem:
            if not await self.gate.take(p.hostname):
                return
            data: dict = {}
            try:
                async with self.client.stream("GET", url) as resp:
                    data["status"] = resp.status_code
                    ct = resp.headers.get("content-type", "").split(";")[0].lower()
                    data["content_type"] = ct
                    data["location"] = resp.headers.get("location", "")
                    body = bytearray()
                    async for part in resp.aiter_bytes():
                        remain = self.a.max_body - len(body)
                        if remain <= 0:
                            break
                        body.extend(part[:remain])
                        if len(body) >= self.a.max_body:
                            break
                    data["bytes"] = len(body)
                    data["body_hash"] = hashlib.sha256(body).hexdigest()
                    if "html" in ct:
                        m = re.search(rb"<title[^>]*>(.*?)</title>", body, re.I | re.S)
                        if m:
                            data["title"] = " ".join(m.group(1).decode("utf-8", "replace").split())[:150]
                    if resp.status_code in (429, 503):
                        self.gate.slow(p.hostname)
                    if data["location"]:
                        self.put_url(data["location"], "redirect", url)
                    if resp.status_code < 400:
                        self.extract(url, ct, bytes(body))
            except (httpx.HTTPError, UnicodeError, OSError) as exc:
                data["error"] = type(exc).__name__
                if p.scheme == "https" and p.path == "/" and not p.query:
                    self.put_url("http://" + p.hostname + "/", "http_fallback")
            finally:
                self.store.finish(url, data)
                self.probed += 1

    async def drain(self, max_probes: int, source: str | None = None):
        LOG.info("HTTP iterative queue, max probes %d", max_probes)
        while self.probed < max_probes and self.gate.count < self.a.max_requests:
            batch_limit = min(self.a.concurrency * 4, max_probes - self.probed)
            items = self.store.pending(batch_limit, source)
            if not items:
                break
            await asyncio.gather(*(self.probe(u) for u in items))
            self.store.commit()
            if self.probed % 100 < len(items):
                LOG.info("probed=%d requests=%d urls=%d", self.probed, self.gate.count, self.store.url_count)

