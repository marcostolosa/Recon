def hostnorm(host: str) -> str:
    host = host.strip().lower().rstrip(".")
    if not host or len(host) > 253:
        raise ValueError("invalid hostname")
    value = host.encode("idna").decode("ascii")
    if not re.fullmatch(r"[a-z0-9-]+(?:\.[a-z0-9-]+)*", value):
        raise ValueError("invalid hostname")
    if any(not x or x[0] == "-" or x[-1] == "-" or len(x) > 63 for x in value.split(".")):
        raise ValueError("invalid hostname")
    return value


class Scope:
    def __init__(self, domain: str, include_subdomains: bool, excludes: list[str]):
        self.root = hostnorm(domain)
        self.include_subdomains = include_subdomains
        self.excludes = tuple(hostnorm(h.lstrip("*.")) for h in excludes if h.strip())

    def allowed_host(self, host: str) -> bool:
        try:
            h = hostnorm(host)
        except (ValueError, UnicodeError):
            return False
        if not (h == self.root or (self.include_subdomains and h.endswith("." + self.root))):
            return False
        return not any(h == ex or h.endswith("." + ex) for ex in self.excludes)

    def url(self, raw: str, base: str | None = None) -> str | None:
        if not raw or len(raw) > 4096:
            return None
        try:
            if any(ord(c) < 32 or ord(c) == 127 for c in raw):
                return None
            raw = raw.strip()
            value = urljoin(base, raw) if base else raw
            p = urlsplit(value)
            if p.scheme.lower() not in {"http", "https"} or not p.hostname or p.username or p.password:
                return None
            h = hostnorm(p.hostname)
            if not self.allowed_host(h):
                return None
            port = p.port
            if port not in (None, 80, 443) or (port == 80 and p.scheme != "http") or (port == 443 and p.scheme != "https"):
                return None
            query = p.query
            path = p.path or "/"
            if "\\" in value or any(ord(c) < 32 or ord(c) == 127 for c in value):
                return None
            # An embedded scheme in the path (e.g. "/40http://host/...") is almost
            # always mangled crawler/gau output, not a real endpoint — drop it.
            if "://" in path:
                return None
            return urlunsplit((p.scheme.lower(), h, path, query, ""))
        except (ValueError, UnicodeError, TypeError):
            return None

    def regex(self) -> str:
        d = re.escape(self.root)
        host = rf"(?:[a-z0-9-]+\.)*{d}" if self.include_subdomains else d
        return rf"(?i)^https?://{host}(?::(?:80|443))?(?:[/?#]|$)"


def score(url: str) -> tuple[int, str]:
    p = urlsplit(url)
    categories = [name for name, (rx, _) in CATEGORIES.items() if rx.search(p.path)]
    base = max((v for name, (_, v) in CATEGORIES.items() if name in categories), default=10)
    names = query_param_names(p.query) if p.query else []
    cache_bust = is_cache_buster(names)
    if cache_bust:
        categories.append("cache_buster")
    if p.query and not cache_bust:
        base += 15
        categories.append("parameterized")
        if HIGH_VALUE_PARAMS.search(p.query):
            base += 20
            categories.append("high_value_param")
        # Params that route to an injection class are the ones worth a scanner.
        # Rank them above JS so the probe budget and scan planner reach them first.
        inj = injection_classes(names)
        if inj:
            base += 40
            categories.append("injectable")
            categories.extend(sorted(inj))
    # JS matters for secrets/endpoints, but a cache-busted bundle is noise, not a lead.
    if p.path.endswith((".js", ".mjs", ".map")) and not cache_bust:
        base += 35
        categories.append("javascript")
    return min(base, 100), ",".join(dict.fromkeys(categories))


class Store:
    def __init__(self, path: Path, max_urls: int):
        self.conn = sqlite3.connect(path)
        self.conn.execute("PRAGMA journal_mode=WAL")
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS hosts(host TEXT PRIMARY KEY, sources TEXT NOT NULL DEFAULT '');
            CREATE TABLE IF NOT EXISTS urls(
                url TEXT PRIMARY KEY, source TEXT NOT NULL, priority INTEGER NOT NULL,
                tags TEXT, checked INTEGER NOT NULL DEFAULT 0, status INTEGER,
                content_type TEXT, bytes INTEGER, title TEXT, location TEXT,
                body_hash TEXT, error TEXT);
            CREATE INDEX IF NOT EXISTS url_queue ON urls(checked, priority DESC);
            CREATE TABLE IF NOT EXISTS url_sources(url TEXT, source TEXT, PRIMARY KEY(url,source));
            CREATE TABLE IF NOT EXISTS secret_indicators(
                kind TEXT, fingerprint TEXT, source TEXT, line INTEGER,
                PRIMARY KEY(kind, fingerprint, source));
            CREATE TABLE IF NOT EXISTS tool_runs(
                name TEXT, argv TEXT, code INTEGER, seconds REAL, details TEXT);
            CREATE TABLE IF NOT EXISTS meta(key TEXT PRIMARY KEY, value TEXT);
            CREATE TABLE IF NOT EXISTS authz(
                url TEXT, identity TEXT, status INTEGER, body_hash TEXT, bytes INTEGER,
                PRIMARY KEY(url, identity));
            CREATE TABLE IF NOT EXISTS findings(kind TEXT, evidence TEXT, PRIMARY KEY(kind,evidence));
        """)
        self.conn.commit()
        self.max_urls = max_urls
        self.url_count = self.conn.execute("SELECT COUNT(*) FROM urls").fetchone()[0]

    def get_int(self, key: str, default: int = 0) -> int:
        row = self.conn.execute("SELECT value FROM meta WHERE key=?", (key,)).fetchone()
        try:
            return int(row[0]) if row else default
        except (ValueError, TypeError):
            return default

    def set_int(self, key: str, value: int) -> None:
        self.conn.execute(
            "INSERT INTO meta(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, str(value)),
        )

    def authz(self, url: str, identity: str, status, body_hash, size) -> None:
        self.conn.execute(
            "INSERT INTO authz VALUES(?,?,?,?,?) ON CONFLICT(url,identity) DO UPDATE SET "
            "status=excluded.status, body_hash=excluded.body_hash, bytes=excluded.bytes",
            (url, identity, status, body_hash, size),
        )

    def host(self, name: str, source: str) -> None:
        old = self.conn.execute("SELECT sources FROM hosts WHERE host=?", (name,)).fetchone()
        existing = set(old[0].split(",")) if old else set()
        existing.discard("")
        existing.add(source)
        self.conn.execute(
            "INSERT INTO hosts(host,sources) VALUES(?,?) ON CONFLICT(host) DO UPDATE SET sources=excluded.sources",
            (name, ",".join(sorted(existing))),
        )

    def url(self, url: str, source: str, probe: bool = True) -> bool:
        existing = self.conn.execute("SELECT checked FROM urls WHERE url=?", (url,)).fetchone()
        if existing:
            self.conn.execute("INSERT OR IGNORE INTO url_sources VALUES(?,?)", (url, source))
            return False
        # Reserve room for active discoveries while retaining a hard total cap.
        passive_cap = max(1, int(self.max_urls * 0.8))
        if self.url_count >= self.max_urls or (
            source == "gau" and self.url_count >= passive_cap
        ):
            return False
        value, tags = score(url)
        self.conn.execute(
            "INSERT INTO urls(url,source,priority,tags,checked) VALUES(?,?,?,?,?)",
            (url, source, value, tags, 0 if probe else 2),
        )
        self.conn.execute("INSERT OR IGNORE INTO url_sources VALUES(?,?)", (url, source))
        self.url_count += 1
        return True

    def pending(self, n: int, source: str | None = None) -> list[str]:
        if source:
            return [
                r[0]
                for r in self.conn.execute(
                    "SELECT u.url FROM urls u JOIN url_sources s ON u.url=s.url WHERE u.checked=0 AND s.source=? ORDER BY u.priority DESC,u.url LIMIT ?",
                    (source, n),
                )
            ]
        return [
            row[0]
            for row in self.conn.execute(
                "SELECT url FROM urls WHERE checked=0 ORDER BY priority DESC, url LIMIT ?", (n,)
            )
        ]

    def finish(self, url: str, data: dict) -> None:
        self.conn.execute(
            "UPDATE urls SET checked=1,status=?,content_type=?,bytes=?,title=?,location=?,body_hash=?,error=? WHERE url=?",
            (
                data.get("status"),
                data.get("content_type"),
                data.get("bytes"),
                data.get("title"),
                data.get("location"),
                data.get("body_hash"),
                data.get("error"),
                url,
            ),
        )

    def secret(self, kind: str, value: str, source: str, line: int) -> None:
        self.conn.execute(
            "INSERT OR IGNORE INTO secret_indicators VALUES(?,?,?,?)",
            (kind, hashlib.sha256(value.encode()).hexdigest(), source, line),
        )

    def tool(self, name: str, argv: list[str], code: int | None, seconds: float, details: str) -> None:
        self.conn.execute(
            "INSERT INTO tool_runs VALUES(?,?,?,?,?)",
            (name, json.dumps(argv), code, seconds, details[:1000]),
        )
        self.conn.commit()

    def commit(self):
        self.conn.commit()

    def count(self, table: str) -> int:
        if table not in {"hosts", "urls", "secret_indicators"}:
            raise ValueError(table)
        return self.conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]


