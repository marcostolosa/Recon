def hostnorm(host: str) -> str:
    host = host.strip().lower().rstrip(".")
    if not host or len(host) > 253:
        raise ValueError("invalid hostname")
    value = host.encode("idna").decode("ascii")
    if not re.fullmatch(r"[a-z0-9-]+(?:\.[a-z0-9-]+)*", value):
        raise ValueError("invalid hostname")
    if any(not x or x[0] == "-" or x[-1] == "-" or len(x) > 63 for x in value.split(".")):
        raise ValueError("invalid hostname")
    return value


class Scope:
    def __init__(self, domain: str, include_subdomains: bool, excludes: list[str]):
        self.root = hostnorm(domain)
        self.include_subdomains = include_subdomains
        self.excludes = tuple(hostnorm(h.lstrip("*.")) for h in excludes if h.strip())

    def allowed_host(self, host: str) -> bool:
        try:
            h = hostnorm(host)
        except (ValueError, UnicodeError):
            return False
        if not (h == self.root or (self.include_subdomains and h.endswith("." + self.root))):
            return False
        return not any(h == ex or h.endswith("." + ex) for ex in self.excludes)

    def url(self, raw: str, base: str | None = None) -> str | None:
        if not raw or len(raw) > 4096:
            return None
        try:
            raw = raw.strip()
            value = urljoin(base, raw) if base else raw
            p = urlsplit(value)
            if p.scheme.lower() not in {"http", "https"} or not p.hostname or p.username or p.password:
                return None
            h = hostnorm(p.hostname)
            if not self.allowed_host(h):
                return None
            port = p.port
            if port not in (None, 80, 443) or (port == 80 and p.scheme != "http") or (port == 443 and p.scheme != "https"):
                return None
            query = urlencode(sorted(parse_qsl(p.query, keep_blank_values=True))) if p.query else ""
            path = p.path or "/"
            if any(ord(c) < 32 for c in path + query):
                return None
            return urlunsplit((p.scheme.lower(), h, path, query, ""))
        except (ValueError, UnicodeError, TypeError):
            return None

    def regex(self) -> str:
        d = re.escape(self.root)
        host = rf"(?:[a-z0-9-]+\.)*{d}" if self.include_subdomains else d
        return rf"(?i)^https?://{host}(?::(?:80|443))?(?:[/?#]|$)"


def score(url: str) -> tuple[int, str]:
    p = urlsplit(url)
    categories = [name for name, (rx, _) in CATEGORIES.items() if rx.search(p.path)]
    base = max((v for name, (_, v) in CATEGORIES.items() if name in categories), default=10)
    if p.query:
        base += 15
        categories.append("parameterized")
        if HIGH_VALUE_PARAMS.search(p.query):
            base += 20
            categories.append("high_value_param")
    if p.path.endswith((".js", ".mjs", ".map")):
        base += 35
        categories.append("javascript")
    return min(base, 100), ",".join(categories)


class Store:
    def __init__(self, path: Path, max_urls: int):
        self.conn = sqlite3.connect(path)
        self.conn.execute("PRAGMA journal_mode=WAL")
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS hosts(host TEXT PRIMARY KEY, sources TEXT NOT NULL DEFAULT '');
            CREATE TABLE IF NOT EXISTS urls(
                url TEXT PRIMARY KEY, source TEXT NOT NULL, priority INTEGER NOT NULL,
                tags TEXT, checked INTEGER NOT NULL DEFAULT 0, status INTEGER,
                content_type TEXT, bytes INTEGER, title TEXT, location TEXT,
                body_hash TEXT, error TEXT);
            CREATE INDEX IF NOT EXISTS url_queue ON urls(checked, priority DESC);
            CREATE TABLE IF NOT EXISTS url_sources(url TEXT, source TEXT, PRIMARY KEY(url,source));
            CREATE TABLE IF NOT EXISTS secret_indicators(
                kind TEXT, fingerprint TEXT, source TEXT, line INTEGER,
                PRIMARY KEY(kind, fingerprint, source));
            CREATE TABLE IF NOT EXISTS tool_runs(
                name TEXT, argv TEXT, code INTEGER, seconds REAL, details TEXT);
            CREATE TABLE IF NOT EXISTS meta(key TEXT PRIMARY KEY, value TEXT);
            CREATE TABLE IF NOT EXISTS authz(
                url TEXT, identity TEXT, status INTEGER, body_hash TEXT, bytes INTEGER,
                PRIMARY KEY(url, identity));
        """)
        self.conn.commit()
        self.max_urls = max_urls
        self.url_count = self.conn.execute("SELECT COUNT(*) FROM urls").fetchone()[0]

    def get_int(self, key: str, default: int = 0) -> int:
        row = self.conn.execute("SELECT value FROM meta WHERE key=?", (key,)).fetchone()
        try:
            return int(row[0]) if row else default
        except (ValueError, TypeError):
            return default

    def set_int(self, key: str, value: int) -> None:
        self.conn.execute(
            "INSERT INTO meta(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, str(value)),
        )

    def authz(self, url: str, identity: str, status, body_hash, size) -> None:
        self.conn.execute(
            "INSERT INTO authz VALUES(?,?,?,?,?) ON CONFLICT(url,identity) DO UPDATE SET "
            "status=excluded.status, body_hash=excluded.body_hash, bytes=excluded.bytes",
            (url, identity, status, body_hash, size),
        )

    def host(self, name: str, source: str) -> None:
        old = self.conn.execute("SELECT sources FROM hosts WHERE host=?", (name,)).fetchone()
        existing = set(old[0].split(",")) if old else set()
        existing.discard("")
        existing.add(source)
        self.conn.execute(
            "INSERT INTO hosts(host,sources) VALUES(?,?) ON CONFLICT(host) DO UPDATE SET sources=excluded.sources",
            (name, ",".join(sorted(existing))),
        )

    def url(self, url: str, source: str, probe: bool = True) -> bool:
        existing = self.conn.execute("SELECT checked FROM urls WHERE url=?", (url,)).fetchone()
        if existing:
            self.conn.execute("INSERT OR IGNORE INTO url_sources VALUES(?,?)", (url, source))
            if probe and existing[0] == 2:
                self.conn.execute("UPDATE urls SET checked=0 WHERE url=?", (url,))
            return False
        # Do not block dynamic/active sources from crawling if queue is full of passive URLs
        if self.url_count >= self.max_urls and source in {"gau", "subfinder", "dns_wordlist"}:
            return False
        value, tags = score(url)
        self.conn.execute(
            "INSERT INTO urls(url,source,priority,tags,checked) VALUES(?,?,?,?,?)",
            (url, source, value, tags, 0 if probe else 2),
        )
        self.conn.execute("INSERT OR IGNORE INTO url_sources VALUES(?,?)", (url, source))
        self.url_count += 1
        return True

    def pending(self, n: int, source: str | None = None) -> list[str]:
        if source:
            return [
                r[0]
                for r in self.conn.execute(
                    "SELECT u.url FROM urls u JOIN url_sources s ON u.url=s.url WHERE u.checked=0 AND s.source=? ORDER BY u.priority DESC,u.url LIMIT ?",
                    (source, n),
                )
            ]
        return [
            row[0]
            for row in self.conn.execute(
                "SELECT url FROM urls WHERE checked=0 ORDER BY priority DESC, url LIMIT ?", (n,)
            )
        ]

    def finish(self, url: str, data: dict) -> None:
        self.conn.execute(
            "UPDATE urls SET checked=1,status=?,content_type=?,bytes=?,title=?,location=?,body_hash=?,error=? WHERE url=?",
            (
                data.get("status"),
                data.get("content_type"),
                data.get("bytes"),
                data.get("title"),
                data.get("location"),
                data.get("body_hash"),
                data.get("error"),
                url,
            ),
        )

    def secret(self, kind: str, value: str, source: str, line: int) -> None:
        self.conn.execute(
            "INSERT OR IGNORE INTO secret_indicators VALUES(?,?,?,?)",
            (kind, hashlib.sha256(value.encode()).hexdigest(), source, line),
        )

    def tool(self, name: str, argv: list[str], code: int | None, seconds: float, details: str) -> None:
        self.conn.execute(
            "INSERT INTO tool_runs VALUES(?,?,?,?,?)",
            (name, json.dumps(argv), code, seconds, details[:1000]),
        )
        self.conn.commit()

    def commit(self):
        self.conn.commit()

    def count(self, table: str) -> int:
        if table not in {"hosts", "urls", "secret_indicators"}:
            raise ValueError(table)
        return self.conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]


class HTMLLinks(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links: list[str] = []
        self.forms: list[dict[str, str]] = []

    def handle_starttag(self, tag, attrs):
        d = dict(attrs)
        for key in (["href"] if tag in {"a", "link"} else ["src"] if tag in {"script", "iframe"} else []):
            if d.get(key):
                self.links.append(d[key])
        if tag == "form":
            self.forms.append({"action": d.get("action", ""), "method": d.get("method", "GET").upper()})


class Throttle:
    def __init__(self, rate: float, max_requests: int):
        self.rate = max(0.1, rate)
        self.cap = max_requests
        self.count = 0
        self.next_at = 0.0
        self.lock = asyncio.Lock()
        self.host_backoff: dict[str, float] = {}

    async def take(self, host: str) -> bool:
        # Never hold the lock across a sleep: a per-host backoff must not stall
        # other hosts, and the global rate gap is enforced by reserving a slot
        # (advancing next_at) atomically before releasing.
        while True:
            async with self.lock:
                if self.count >= self.cap:
                    return False
                now = time.monotonic()
                delay = max(0.0, self.next_at - now, self.host_backoff.get(host, 0) - now)
                if delay <= 0:
                    self.count += 1
                    self.next_at = now + (1.0 / self.rate)
                    return True
            await asyncio.sleep(delay)

    def slow(self, host: str, seconds: float = 15) -> None:
        self.host_backoff[host] = max(self.host_backoff.get(host, 0), time.monotonic() + seconds)


class Recon:
    def __init__(self, a):
        self.a = a
        self.scope = Scope(a.domain, a.subdomains, a.exclude)
        self.out = Path(a.out).resolve()
        self.out.mkdir(parents=True, exist_ok=True)
        if os.name == "posix":
            os.chmod(self.out, 0o700)
        self.wildcard_dns: dict = {}
        self.soft404: dict[str, dict] = {}
        self.js_dir = self.out / "js"
        self.js_dir.mkdir(exist_ok=True)
        self.tool_dir = self.out / "tools"
        self.tool_dir.mkdir(exist_ok=True)
        self.store = Store(self.out / "state.sqlite", a.max_urls)
        # Resume honours a cumulative request/probe ceiling across runs so repeated
        # resumes never exceed the authorized budget against the target.
        self.prior_requests = self.store.get_int("requests_total", 0)
        self.prior_probes = self.store.get_int("probes_total", 0)
        self.gate = Throttle(a.rate, a.max_requests)
        self.gate.count = self.prior_requests
        self.sem = asyncio.Semaphore(a.concurrency)
        self.dns_sem = asyncio.Semaphore(a.dns_concurrency)
        self.dns_ok: dict[str, bool] = {}
        self.probed = self.prior_probes
        self.js_saved: set[str] = set()
        self.takeover_hits: list[dict] = []
        self.bypass_hits: list[dict] = []
        self.bola_findings: list[dict] = []

        headers = {"User-Agent": a.user_agent}
        for h in a.header or []:
            if ":" in h:
                k, v = h.split(":", 1)
                headers[k.strip()] = v.strip()

        self.client = httpx.AsyncClient(
            timeout=a.timeout,
            verify=True,
            follow_redirects=False,
            trust_env=False,
            headers=headers,
            limits=httpx.Limits(max_connections=a.concurrency, max_keepalive_connections=a.concurrency),
        )

    def scope_config(self) -> dict:
        return {
            "domain": self.scope.root,
            "subdomains": bool(self.a.subdomains),
            "exclude": sorted(self.a.exclude or []),
            "exclude_path": sorted(self.a.exclude_path or []),
            "allow_private": bool(self.a.allow_private),
        }

    def put_url(self, raw: str, source: str, base: str | None = None, probe: bool = True) -> None:
        u = self.scope.url(raw, base)
        if not u:
            return
        path = urlsplit(u).path
        if any(path.startswith(prefix) for prefix in self.a.exclude_path):
            return
        self.store.url(u, source, probe=probe and not bool(UNSAFE_GET.search(path)))
        host = urlsplit(u).hostname
        if host:
            self.store.host(host, source)

    def put_host(self, raw: str, source: str) -> None:
        try:
            clean = hostnorm(str(raw).strip().lstrip("*."))
        except (ValueError, UnicodeError):
            return
        if self.scope.allowed_host(clean):
            self.store.host(clean, source)

    async def command(self, name: str, argv: list[str], timeout: int | None = None) -> Path | None:
        if not shutil.which(argv[0]):
            LOG.warning("%s missing in PATH; skipped", argv[0])
            return None
        path = self.tool_dir / f"{name}.stdout"
        errpath = self.tool_dir / f"{name}.stderr"
        started = time.monotonic()
        code = None
        details = ""
        try:
            with path.open("wb") as stdout, errpath.open("wb") as stderr:
                proc = await asyncio.create_subprocess_exec(*argv, stdout=stdout, stderr=stderr)
                try:
                    code = await asyncio.wait_for(proc.wait(), timeout=timeout or self.a.tool_timeout)
                except asyncio.TimeoutError:
                    proc.kill()
                    await proc.wait()
                    details = "timeout"
            if code not in (0, 1):
                details = (details + " " + errpath.read_text(errors="replace")[-500:]).strip()
                LOG.warning("tool %s exit=%s: %s", name, code, details[:180])
        except OSError as exc:
            details = str(exc)
            LOG.warning("tool %s: %s", name, exc)
        self.store.tool(name, argv, code, time.monotonic() - started, details)
        return path if path.exists() else None

    def ingest_lines(self, path: Path | None, source: str, kind: str = "url") -> None:
        if not path:
            return
        with path.open("r", encoding="utf-8", errors="replace") as f:
            for i, line in enumerate(f):
                if i >= self.a.max_import_lines:
                    break
                raw = line.strip().split()[0] if line.strip() else ""
                if not raw:
                    continue
                if kind == "host":
                    self.put_host(raw, source)
                else:
                    self.put_url(raw, source)
        self.store.commit()

    async def ct_provider(self, name: str, url: str, params: dict):
        try:
            async with self.client.stream("GET", url, params=params) as r:
                if r.status_code != 200:
                    LOG.warning("%s HTTP %s", name, r.status_code)
                    return
                size = 0
                chunks = []
                async for chunk in r.aiter_bytes():
                    size += len(chunk)
                    if size > MAX_CT:
                        LOG.warning("%s exceeded response cap", name)
                        return
                    chunks.append(chunk)
            records = json.loads(b"".join(chunks))
            for rec in records:
                names = rec.get("dns_names", []) if name == "certspotter" else str(rec.get("name_value", "")).splitlines()
                for host in names:
                    self.put_host(str(host), name)
            self.store.commit()
        except (httpx.HTTPError, ValueError, json.JSONDecodeError) as exc:
            LOG.warning("%s error: %s", name, type(exc).__name__)

    async def passive(self):
        self.put_host(self.scope.root, "seed")
        self.put_url("https://" + self.scope.root + "/", "seed")
        LOG.info("passive enumeration: %s", self.scope.root)
        if not self.a.no_enum:
            if self.a.ct:
                await self.ct_provider("crtsh", "https://crt.sh/", {"q": "%." + self.scope.root, "output": "json"})
                await self.ct_provider(
                    "certspotter",
                    "https://api.certspotter.com/v1/issuances",
                    {"domain": self.scope.root, "include_subdomains": "true", "expand": "dns_names"},
                )
            if self.a.subfinder:
                argv = ["subfinder", "-d", self.scope.root, "-silent", "-rl", str(max(1, int(self.a.rate)))]
                if self.a.subfinder_all:
                    argv.append("-all")
                self.ingest_lines(await self.command("subfinder", argv), "subfinder", "host")
            if self.a.amass:
                self.ingest_lines(
                    await self.command("amass", ["amass", "enum", "-passive", "-d", self.scope.root]),
                    "amass",
                    "host",
                )
            if self.a.gau:
                argv = ["gau", "--threads", "2"]
                if self.a.subdomains:
                    argv.append("--subs")
                argv.append(self.scope.root)
                self.ingest_lines(await self.command("gau", argv), "gau")
        if self.a.subdomain_wordlist and self.a.subdomains:
            with open(self.a.subdomain_wordlist, encoding="utf8") as f:
                for i, word in enumerate(f):
                    if i >= self.a.max_dns_words:
                        break
                    word = word.strip().lower()
                    if re.fullmatch(r"[a-z0-9-]{1,63}(?:\.[a-z0-9-]{1,63})*", word):
                        self.put_host(word + "." + self.scope.root, "dns_wordlist")
        self.store.commit()

    async def resolves(self, host: str) -> bool:
        if host in self.dns_ok:
            return self.dns_ok[host]
        async with self.dns_sem:
            try:
                records = await asyncio.wait_for(
                    asyncio.get_running_loop().getaddrinfo(host, None, type=socket.SOCK_STREAM),
                    timeout=self.a.timeout,
                )
                ips = {row[4][0] for row in records}
                valid = bool(ips) and (self.a.allow_private or all(ipaddress.ip_address(i).is_global for i in ips))
            except (OSError, asyncio.TimeoutError, ValueError):
                valid = False
            self.dns_ok[host] = valid
            return valid

    async def detect_dns_wildcard(self):
        observations = []
        for _ in range(2):
            candidate = secrets.token_hex(10) + "." + self.scope.root
            try:
                rows = await asyncio.wait_for(
                    asyncio.get_running_loop().getaddrinfo(candidate, None, type=socket.SOCK_STREAM),
                    timeout=self.a.timeout,
                )
                observations.append(sorted({r[4][0] for r in rows}))
            except (OSError, asyncio.TimeoutError):
                observations.append([])
        # Wildcard is suspected if both non-existent queries returned valid IPs
        possible = bool(observations[0] and observations[1])
        self.wildcard_dns = {"possible": possible, "answers": observations}
        if possible:
            LOG.warning("DNS wildcard suspected. Wordlist results need manual validation")

