    def _scan_argv(self, tool: str, url: str, scan_dir: Path, idx: int = 0) -> list[str]:
        """Single source of truth for per-URL scanner invocations — shared by the
        manual --scanners path, the generated scan_plan.sh, and --auto-scan. Depth
        comes from the --scan-profile; speed from --rate (delay) and thread count."""
        if self.permitted_url(url) is None:
            raise ValueError("scanner target blocked by policy")
        delay = round(1.0 / self.a.rate, 3)
        t = self.a.timeout
        prof = SCAN_PROFILES[self.a.scan_profile][tool]
        headers = self.headers_for(url)
        bulk_headers = "\n".join(f"{k}: {v}" for k, v in headers.items())
        threads = min(self.a.concurrency, prof.get("threads", prof.get("worker", 1)))
        if tool == "sqlmap":
            argv = ["sqlmap", "-u", url, "--batch", f"--level={prof['level']}", f"--risk={prof['risk']}",
                    f"--threads={threads}", "--retries=0", f"--timeout={t}", f"--delay={delay}",
                    "--ignore-redirects", "--headers", bulk_headers,
                    "--disable-coloring", f"--output-dir={scan_dir / 'sqlmap'}"]
            return argv
        if tool == "ghauri":
            return ["ghauri", "-u", url, "--batch", "--level", str(prof["level"]), "--confirm",
                    "--threads", str(threads), "--timeout", str(t), "--delay", str(delay),
                    "--headers", bulk_headers]
        if tool == "commix":
            return ["commix", "--batch", "-u", url, "--level", str(prof["level"]), f"--timeout={t}",
                    "--delay", str(delay), "--ignore-redirects", "--headers", bulk_headers]
        if tool == "dalfox":
            argv = ["dalfox", "url", url, "--worker", str(threads), "--delay", str(int(delay * 1000)),
                    "--timeout", str(t), "--format", "jsonl", "--output", str(scan_dir / f"dalfox_{idx}.jsonl")]
            for key, value in headers.items():
                argv += ["-H", f"{key}: {value}"]
            if not prof["mining"]:
                argv += ["--skip-mining-all"]
            if prof["deep_domxss"]:
                argv.append("--deep-domxss")
            return argv
        raise ValueError(tool)

    def _nuclei_argv(self, input_file: Path) -> list[str]:
        cmd = ["nuclei", "-l", str(input_file), "-rl", str(max(1, int(self.a.rate))), "-c", "1",
               "-timeout", str(self.a.timeout), "-retries", "0", "-ni", "-dr", "-no-color", "-jsonl", "-or"]
        for key, value in self.public_headers.items():
            cmd += ["-H", f"{key}: {value}"]
        if self.a.nuclei_tags:
            cmd.extend(["-tags", self.a.nuclei_tags])
        if self.a.nuclei_templates:
            cmd.extend(["-t", self.a.nuclei_templates])
        return cmd

    async def scanners(self):
        if not self.a.scanners:
            return
        if self.a.exclude or self.a.exclude_path:
            LOG.warning("external scanners skipped: cannot guarantee configured exclusions; plan remains reviewable")
            return
        scan_dir = self.out / "scanners"
        scan_dir.mkdir(exist_ok=True)
        live = [
            r[0]
            for r in self.store.conn.execute(
                "SELECT url FROM urls WHERE status BETWEEN 200 AND 399 ORDER BY priority DESC LIMIT ?",
                (self.a.scan_limit,),
            )
        ]
        params = [
            r[0]
            for r in self.store.conn.execute(
                "SELECT url FROM urls WHERE status BETWEEN 200 AND 399 AND instr(url,'?')>0 ORDER BY priority DESC LIMIT ?",
                (self.a.scan_limit,),
            )
        ]
        for tool in self.a.scanners:
            if tool == "nuclei":
                if not self.a.nuclei_tags and not self.a.nuclei_templates:
                    LOG.warning("nuclei needs reviewed --nuclei-tags or --nuclei-templates; skipped")
                    continue
                targets = scan_dir / "nuclei-input.txt"
                targets.write_text("\n".join(live) + "\n", encoding="utf8")
                await self.command("scanner_nuclei", self._nuclei_argv(targets))
            elif tool in EXECUTABLE_SCAN_TOOLS:
                if not params:
                    continue
                if not await self.ensure_tool(tool):
                    LOG.warning("%s missing in PATH; skipped", tool)
                    continue
                for i, u in enumerate(params):
                    if self.permitted_url(u) is None or not await self.resolves(urlsplit(u).hostname):
                        continue
                    if tool == "ghauri" and any(k not in PUBLIC_HEADERS for k in self.headers_for(u)):
                        LOG.warning("ghauri skipped for authenticated target: redirect policy is not guaranteed")
                        continue
                    await self.command(f"scanner_{tool}_{i}", self._scan_argv(tool, u, scan_dir, i))

    def classify_url(self, url: str) -> tuple[dict[str, tuple], list[str]]:
        names = [k for k, _ in parse_qsl(urlsplit(url).query, keep_blank_values=True)]
        hits = {cls: tools for cls, (rx, tools) in INJECTION_ROUTES.items() if any(rx.fullmatch(n) for n in names)}
        return hits, names

    async def plan_scans(self):
        """Classify live parameterized endpoints and propose which tool to run where.
        Always writes a reviewable plan (JSON + shell script). With --auto-scan it also
        launches the executable tools that are present in PATH."""
        # Scan over a generous pool of live parameterized URLs (ordered by priority),
        # not just the top scan_plan_limit: otherwise cache-busters / non-injectable
        # params at the top of the ranking crowd out the injectable endpoints and the
        # plan comes back empty. We stop once scan_plan_limit matches are collected.
        pool = max(self.a.scan_plan_limit * 20, 500)
        rows = [
            r[0]
            for r in self.store.conn.execute(
                "SELECT url FROM urls WHERE checked=1 AND status BETWEEN 200 AND 399 AND instr(url,'?')>0 "
                "AND source!='soft404_control' ORDER BY priority DESC LIMIT ?",
                (pool,),
            )
        ]
        allowed = set(self.a.scan_tools) if self.a.scan_tools else None
        plan: list[dict] = []
        tool_targets: dict[str, list[str]] = defaultdict(list)
        seen: set[tuple] = set()
        for url in rows:
            if len(plan) >= self.a.scan_plan_limit:
                break
            if self.permitted_url(url) is None or self.is_soft404(url):
                continue
            hits, names = self.classify_url(url)
            if not hits:
                continue
            tools = sorted({t for tset in hits.values() for t in tset})
            if allowed is not None:
                tools = [t for t in tools if t in allowed or t.split("-")[0] in allowed]
            if not tools:
                continue
            # Strip other researchers' payloads from the values, then collapse the
            # many variants of one endpoint (id=0, id=1, id=0+and+1=1--) into a single
            # clean target so the scanner runs once per (path, params), not per variant.
            target = sanitize_scan_url(url)
            key = (urlsplit(target).path, tuple(sorted(names)))
            if key in seen:
                continue
            seen.add(key)
            plan.append({"url": target, "classes": sorted(hits), "params": names, "suggested_tools": tools})
            for t in tools:
                if t in EXECUTABLE_SCAN_TOOLS:
                    tool_targets[t].append(target)
        self.scan_plan_count = len(plan)
        self.plan_items = list(plan)
        scan_dir = self.out / "scanners"
        scan_dir.mkdir(exist_ok=True)
        atomic_text(self.out / "scan_plan.json", "".join(json.dumps(x, ensure_ascii=False) + "\n" for x in plan))
        self._write_scan_script(plan, tool_targets, scan_dir)
        suggested = sorted({t for p in plan for t in p["suggested_tools"]})
        LOG.info("scan planner: %d endpoints, tools suggested: %s", len(plan), ", ".join(suggested))
        if _RICH and CONSOLE.is_terminal and plan:
            print_scan_plan(plan)
        if self.a.auto_scan:
            await self._run_plan(tool_targets, scan_dir)
        else:
            LOG.info("scan plan written (review scan_plan.sh); pass --auto-scan to execute automatically")

    def _write_scan_script(self, plan, tool_targets, scan_dir: Path) -> None:
        lines = [
            "#!/usr/bin/env bash",
            "# ReconForge scan plan — REVIEW BEFORE RUNNING. Authorized targets only.",
            "# These are proposals routed from discovered parameters; adjust level/risk as the program allows.",
            "set -u",
            "",
        ]
        for tool in sorted(tool_targets):
            lines.append(f"# === {tool} ===")
            for i, url in enumerate(dict.fromkeys(tool_targets[tool])):
                argv = self._scan_argv(tool, url, scan_dir, i)
                command = self.shell_command(argv)
                if self.a.exclude or self.a.exclude_path:
                    lines.append("# DISABLED: external tool cannot guarantee exclusions")
                    lines.extend("# " + line for line in command.splitlines())
                elif tool == "ghauri" and any(k not in PUBLIC_HEADERS for k in self.headers_for(url)):
                    lines.append("# DISABLED: authenticated ghauri redirects require manual review")
                    lines.extend("# " + line for line in command.splitlines())
                else:
                    lines.append(command)
            lines.append("")
        # Suggestions that stay manual / need template review
        manual = [p for p in plan if any(t in ("manual", "nuclei-ssrf", "nuclei-lfi") for t in p["suggested_tools"])]
        if manual:
            lines.append("# === manual review (SSRF/LFI/redirect — verify by hand or with reviewed nuclei templates) ===")
            for p in manual:
                comment = f"{p['url']}  [{','.join(p['classes'])}]  params={','.join(p['params'])}"
                lines.extend("#   " + line for line in comment.splitlines())
        atomic_text(self.out / "scan_plan.sh", "\n".join(lines) + "\n")

    async def _run_plan(self, tool_targets, scan_dir: Path) -> None:
        if self.a.exclude or self.a.exclude_path:
            LOG.warning("auto-scan skipped: external tools cannot guarantee configured exclusions")
            return
        for tool in sorted(tool_targets):
            if tool not in EXECUTABLE_SCAN_TOOLS:
                continue
            if not await self.ensure_tool(tool):
                LOG.warning("auto-scan: %s not in PATH; skipped (%d targets)", tool, len(set(tool_targets[tool])))
                continue
            for i, url in enumerate(dict.fromkeys(tool_targets[tool])):
                if self.permitted_url(url) is None or not await self.resolves(urlsplit(url).hostname):
                    continue
                if tool == "ghauri" and any(k not in PUBLIC_HEADERS for k in self.headers_for(url)):
                    LOG.warning("ghauri skipped for authenticated target: redirect policy is not guaranteed")
                    continue
                LOG.info("auto-scan %s -> %s", tool, url)
                await self.command(f"autoscan_{tool}_{i}", self._scan_argv(tool, url, scan_dir, i))

    async def offline_secrets(self):
        if not any((self.a.gitleaks, self.a.trufflehog)) or not any(self.js_dir.glob("*.js")):
            return
        if self.a.gitleaks:
            await self.command(
                "gitleaks",
                [
                    "gitleaks",
                    "dir",
                    str(self.js_dir),
                    "--redact",
                    "--report-format",
                    "json",
                    "--report-path",
                    str(self.tool_dir / "gitleaks.json"),
                ],
            )
        if self.a.trufflehog:
            await self.command(
                "trufflehog",
                ["trufflehog", "filesystem", str(self.js_dir), "--no-verification", "--json"],
            )

    async def run(self):
        try:
            with RunLock(self.out / ".run.lock"):
                self.validate_scope_config()
                self.gate.count = self.store.get_int("requests_total", 0)
                self.probed = self.store.get_int("probes_total", 0)
                await self._run_locked()
        finally:
            await self.aclose()

    async def _run_locked(self):
        existing = self.out / "run_config.json"
        if not existing.exists():
            atomic_text(existing, json.dumps(self.scope_config(), indent=2))
        dashboard = VisualDashboard(self) if getattr(self.a, "visual", False) else None
        if dashboard:
            await dashboard.start()
        interrupted = False
        try:
            self.current_phase = "Fase 1 • Descoberta Passiva & DNS"
            print_phase("Fase 1", "Descoberta Passiva & DNS Enumeration")
            await self.passive()
            if self.a.passive_only:
                return
            self.current_phase = "Fase 2 • Resolução DNS & Probing Inicial"
            print_phase("Fase 2", "Resolução DNS, Pinning & Probing Inicial")
            await self.seed_hosts()
            await self.drain(min(self.a.max_probes, self.a.initial_probes))
            self.current_phase = "Fase 3 • Crawling, Extração JS & Renderização"
            print_phase("Fase 3", "Crawling Profundo, Extração JS & Renderização")
            await self.crawl_katana()
            discovery_cap = (
                self.a.max_probes
                if not self.a.fuzz
                else max(self.a.initial_probes, int(self.a.max_probes * 0.7))
            )
            await self.drain(discovery_cap)
            await self.browser()
            await self.drain(discovery_cap)
            if self.a.fuzz or self.a.ffuf:
                self.current_phase = "Fase 4 • Fuzzing & Calibração Soft-404"
                print_phase("Fase 4", "Fuzzing Contextual & Calibração Soft-404")
            await self.wordlist_fuzz()
            await self.ffuf()
            await self.drain(self.a.max_probes)
            self.current_phase = "Fase 5 • Verificações (Takeover, 403, BOLA, Secrets)"
            print_phase("Fase 5", "Verificações de Segurança (Takeover, 403 Bypass, BOLA, Secrets)")
            await self.takeover()
            await self.bypass_403()
            await self.bola()
            await self.offline_secrets()
            self.current_phase = "Fase 6 • Scan Planner & Scanners"
            print_phase("Fase 6", "Scan Planner & Scanners Direcionados")
            await self.scanners()
            await self.plan_scans()
        except (KeyboardInterrupt, asyncio.CancelledError):
            interrupted = True
            raise
        finally:
            if interrupted:
                self.current_phase = "Pausado (Ctrl+C) • Progresso Salvo"
                if _RICH and CONSOLE.is_terminal:
                    print_phase("Pausa", "Execução Interrompida — Salvando Estado no SQLite")
            else:
                self.current_phase = "Concluído • Relatório & Dashboard Gerados"
                print_phase("Fase 7", "Exportação de Artefatos & Relatório Final")
            self.export()
            if dashboard:
                try:
                    await asyncio.sleep(0.5)
                    await dashboard.stop()
                except Exception:
                    pass
                if not interrupted:
                    ui_event("VISUAL-UI", f"Dashboard estático salvo em: [bold white]{self.out / 'dashboard.html'}[/bold white]", C_OK)


