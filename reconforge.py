    for cand in candidates:
        s = str(cand)
        norm = os.path.normcase(os.path.normpath(s))
        if cand.is_dir() and norm not in norm_existing:
            added.append(s)
            norm_existing.add(norm)
    if added:
        os.environ["PATH"] = os.pathsep.join(added + parts)


